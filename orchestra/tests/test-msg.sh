#!/usr/bin/env bash
set -u
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
S=$(mktemp -d "${TMPDIR:-/tmp}/orchestra-test-msg.XXXXXX"); trap 'rm -rf $S' EXIT; cd $S  # unique: workers run suites concurrently
export ORCH_HOME=$S/home; O=$ROOT/bin/orch; H=$ROOT/hooks/push-guard.py
hard(){ perl -MPOSIX -e '$t = shift; $p = fork // die; unless ($p) { POSIX::setsid(); exec @ARGV or exit 127 } $SIG{ALRM} = sub { kill 9, -$p, $p; exit 137 }; alarm $t; waitpid $p, 0; exit($? & 127 ? 128 + ($? & 127) : $? >> 8)' 60 "$@"; }  # every hook call under a 60s wall clock (SIGKILL: blocking signals can't dodge it): a hang fails the case, never stalls the suite
export ORCH_PORT_BASE=${ORCH_TEST_PORT_BASE:-$((30000 + $$ % 300 * 100))} ORCH_PORT_SPAN=90  # private port block, so this suite's allocations never collide with another's
mkdir -p $S/stub; for x in caffeinate xcrun osascript; do printf '#!/bin/sh\nexit 0\n' > $S/stub/$x; chmod +x $S/stub/$x; done; export PATH=$S/stub:$PATH  # never the real caffeinate/simulators
git init -q --bare -b main origin.git; git clone -q origin.git repo 2>/dev/null; cd repo; echo a>a; git add .; git commit -qm i; git push -q origin main; git remote set-head origin main
RUN=$($O new-run --repo . --title m --coordinator workspace:7); git worktree add -q .claude/worktrees/w -b w origin/main; W=$S/repo/.claude/worktrees/w
$O register --worktree $W --run $RUN --slice s >/dev/null
P=0; F=0
t(){ out=$(python3 -c 'import json,sys;print(json.dumps({"tool_name":"Bash","cwd":sys.argv[1],"tool_input":{"command":sys.argv[2]}}))' "$1" "$2" | hard python3 $H 2>&1); r=$?; [ $r = $3 ] && { P=$((P+1)); echo "ok   $4"; } || { F=$((F+1)); echo "FAIL $4 (got $r) $out"; }; }
t $W 'cmux agent message workspace:7 --from x "PROGRESS: step 3 gates green"' 0 "tagged report to own coordinator"
t $W 'cmux agent message workspace:7 --from x -- "QUESTION: which copy?"' 0 "question with -- separator"
t $W 'cmux agent message workspace:7 "please merge my branch now"' 2 "untagged instruction to coordinator"
t $W 'cmux agent message workspace:9 "PROGRESS: hi"' 2 "message to another workspace (worker)"
t $W 'cmux agent message other-worker-title "MERGED: x"' 2 "message to worker by title"
t $W 'cmux send --workspace workspace:9 "git push"' 2 "typing into another terminal"
t $W 'cmux new-workspace --command claude' 2 "spawning workspaces"
t $W 'orch broadcast --run x "hi"' 2 "worker broadcast"
t $W 'cd / && cmux agent message workspace:9 "PROGRESS: x"' 2 "cd-escape still restricted"
t $W 'cmux agent message --reply-to abc123 "QUESTION: ok?"' 0 "tagged reply"
echo "-- C7: a worker runs only the allowed cmux commands"
python3 -c 'import json,sys; p=sys.argv[1]; d=json.load(open(p)); d["workspace"]="surface:5"; json.dump(d, open(p, "w"))' "$(git -C $W rev-parse --git-dir)/orchestra-owner.json"
t $W 'cmux identify --json' 0 "identify allowed"
t $W 'cmux notify --title slice --body "gates green"' 0 "notify allowed"
t $W 'cmux notify --body send' 0 "notify whose argument names a verb allowed"
t $W 'cmux set-status slice-s gates' 0 "set-status allowed"
t $W 'cmux set-progress 0.5 --label gates' 0 "set-progress allowed"
t $W 'cmux read-screen --surface surface:5 --lines 20' 0 "read-screen of its own surface allowed"
t $W 'cmux read-screen --surface surface:9 --lines 20' 2 "read-screen of another surface denied"
t $W 'cmux read-screen --lines 20' 2 "read-screen without its own --surface denied"
t $W 'cmux read-screen --surface surface:5 --workspace workspace:9' 2 "read-screen with another --workspace denied"
t $W 'cmux read-screen --surface=surface:9' 2 "read-screen --surface=<other> denied"
t $W 'cmux set-status --workspace workspace:9 x y' 2 "set-status on another workspace denied"
t $W 'cmux set-progress 0.5 --window window:2' 2 "set-progress on another window denied"
t $W 'cmux notify --workspace workspace:9 --body x' 2 "notify to another workspace denied"
t $W 'cmux notify --surface surface:9 --body x' 2 "notify to another surface denied"
t $W 'cmux notify --surface surface:5 --body x' 0 "notify to its own surface allowed"
t $W 'CMUX_SURFACE_ID=surface:9 cmux notify --body x' 2 "a CMUX_* env prefix retargeting cmux denied"
t $W 'export CMUX_WORKSPACE_ID=workspace:9; cmux set-status k v' 2 "an exported CMUX_* retargeting cmux denied"
t $W 'read CMUX_SURFACE_ID <<< surface:9; export CMUX_SURFACE_ID; cmux notify --body x' 2 "a CMUX_* set by read + export denied"
t $W 'printf -v CMUX_SURFACE_ID surface:9; cmux notify --body x' 2 "a CMUX_* set by printf -v denied"
t $W 'cmux notify $ARGS --body x' 2 "a \$-built target argument denied"
t $W "bash -c '\$0 tree --all' cmux" 2 "cmux passed as \$0 to bash -c denied"
t $W 'command cmux tree' 2 "command cmux tree denied"
t $W 'cmux agent message workspace:7 --from x "PROGRESS: dropped the CMUX_SURFACE_ID= prefix"' 0 "a report naming CMUX_X= allowed"
t $W 'git commit -qm "no CMUX_SOCKET= override for the stub"' 0 "a commit message naming CMUX_X= allowed"
t $W "grep -rn 'CMUX_SURFACE_ID=' skills/" 0 "grep for CMUX_X= allowed"
t $W 'command -v cmux' 0 "command -v cmux allowed"
t $W 'command -v cmux >/dev/null && echo yes' 0 "command -v cmux with a redirection allowed"
t $W 'find . -name cmux -type f' 0 "find -name cmux allowed"
echo "-- worker cmux: lookups, file names and reads; NAME= prefixes; text that may run"
t $W 'eval "cmux tree --all"' 2 "eval denied"
t $W 'echo "today $(date)"' 0 "a \$( ) argument to a literal program allowed"
t $W 'X=$(date) ls' 0 "a \$( ) assignment before a literal program allowed"
t $W 'ls "$HOME" | wc -l' 0 "\$VAR arguments allowed"
t $W 'timeout -v 5 command cmux tree' 2 "a -v of another wrapper isn't a command -v lookup"
t $W 'env -v command cmux tree' 2 "env -v command cmux tree denied"
t $W 'X=$(command -v jq) cmux tree' 2 "a command -v inside \$( ) doesn't skip the cmux after it"
t $W 'ORCH_CMUX=./stub/cmux bash run-tests.sh' 2 "ORCH_CMUX=<stub> glued to a cmux word: known false deny (export it first)"
t $W 'echo ${CMUX_PORT}; cmux identify' 0 "reading \${CMUX_*} allowed"
t $W "bash -c 'X=1;cmux tree --all'" 2 "an assignment glued before cmux in bash -c text denied"
t $W "sh -c 'A=1;cmux notify --surface surface:9 --body x'" 2 "…aimed at another surface denied"
t $W 'bash -c "cd /tmp && A=b&&cmux tree --all"' 2 "…after && denied"
t $W 'X=1;cmux tree --all; echo $(date)' 2 "…in a command with a \$( ) denied"
t $W "python3 -c \"import subprocess;subprocess.run(args='cmux tree --all',shell=True)\"" 2 "cmux in python -c text denied"
t $W 'bash <<'"'"'EOF'"'"'
A=1;cmux tree --all
EOF' 2 "…in a heredoc fed to bash denied"
t $S/repo 'CMUX_SURFACE_ID=surface:9 cmux notify --body x' 0 "coordinator CMUX_* env unrestricted"
t $W 'cmux tree --all' 2 "tree denied"
t $W 'cmux rpc surface.send_text "{}"' 2 "rpc denied"
t $W 'cmux pipe-pane --surface surface:9 "cat > x"' 2 "pipe-pane denied"
t $W 'cmux set-hook after-command "sh x"' 2 "set-hook denied"
t $W 'cmux send --surface surface:5 "y"' 2 "send denied (even to its own surface)"
t $W 'cmux list-workspaces' 2 "list-workspaces denied"
t $W 'cmux rename-workspace x' 2 "rename-workspace denied"
t $W 'cmux clear-status slice-s' 2 "clear-status (not in the allowed set) denied"
t $W 'cmux agent messages off' 2 "agent messages (plural) denied"
t $W 'cmux --json identify' 2 "an option before the verb denied"
t $W 'cmux' 2 "bare cmux denied"
t $W 'cmux "agent message" workspace:7 workspace:7 "PROGRESS: x"' 2 "a quoted one-word \"agent message\" verb denied"
t $W 'cmux identify; cmux tree' 2 "an allowed command chained with another verb denied"
out=$(python3 -c 'import json,sys;print(json.dumps({"tool_name":"Bash","cwd":sys.argv[1],"tool_input":{"command":"cmux tree"}}))' $W | hard python3 $H 2>&1)
echo "$out" | grep -q 'agent message' && echo "$out" | grep -q 'identify' && echo "$out" | grep -q 'set-progress' && echo "$out" | grep -q 'read-screen' && { P=$((P+1)); echo "ok   denial names the allowed set"; } || { F=$((F+1)); echo "FAIL denial names the allowed set: $out"; }
t $S/repo 'cmux tree --all' 0 "coordinator cmux tree unrestricted"
t $S/repo 'cmux read-screen --surface surface:9' 0 "coordinator read-screen of any surface"
t $S/repo 'cmux agent message workspace:9 "REBASE: main moved"' 0 "coordinator can command workers"
t $S/repo 'cmux send --workspace workspace:9 "x"' 0 "coordinator unrestricted"
echo "PASSED $P FAILED $F"; [ $F = 0 ]
