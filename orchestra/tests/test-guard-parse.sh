#!/usr/bin/env bash
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
# push-guard parses pushes fail-closed: continuations, global options, flag clusters, quoted/extra refspecs.
set -u
S=$(mktemp -d "${TMPDIR:-/tmp}/orchestra-test-guard-parse.XXXXXX"); trap 'rm -rf $S' EXIT; cd $S  # unique: workers run suites concurrently
export ORCH_HOME=$S/home; O=$ROOT/bin/orch; H=$ROOT/hooks/push-guard.py
P=0; F=0
expect(){ # expect <label> <want: allow|ask|deny|silent> <cwd> <cmd>
  out=$(python3 -c 'import json,sys;print(json.dumps({"tool_name":"Bash","cwd":sys.argv[1],"tool_input":{"command":sys.argv[2]}}))' "$3" "$4" | python3 $H 2>&1); rc=$?
  got=silent; [ $rc = 2 ] && got=deny; echo "$out" | grep -q '"allow"' && got=allow; echo "$out" | grep -q '"ask"' && got=ask
  if [ $got = $2 ]; then P=$((P+1)); echo "ok   $1"; else F=$((F+1)); echo "FAIL $1: want $2 got $got :: $out"; fi; }
ok(){ if eval "$2" >/dev/null 2>&1; then P=$((P+1)); echo "ok   $1"; else F=$((F+1)); echo "FAIL $1"; fi; }
V="ver""dict"  # keep the evidence-writer pair out of this file's own command text
NL=$'\n'; BS=$'\\\n'  # bare newline (command separator) and backslash-newline (continuation)

git init -q --bare -b main origin.git; git clone -q origin.git repo 2>/dev/null; cd repo; R=$S/repo
echo 'echo ok' > gate.sh; echo a > a.txt; git add .; git commit -qm init; git push -q origin main; git remote set-head origin main
echo b > a.txt; git commit -qam b

echo "-- main checkout, no tier: force/delete stays denied however it is spelled"
expect "plain push allowed" allow $R "git push origin main"
expect "continuation joined, still a normal push" allow $R "git push origin main ${BS}  -q"
expect "continuation hiding --force → deny" deny $R "git push origin HEAD:main ${BS}  --force"
expect "continuation hiding a :delete refspec → deny" deny $R "git push origin HEAD:main ${BS}  :main"
expect "bare newline separates commands (compound: no decision, H4)" silent $R "git push origin main${NL}echo --force"
expect "quoted +refspec → deny" deny $R "git push origin \"+HEAD:main\""
expect "single-quoted :refspec → deny" deny $R "git push origin ':main'"
expect "combined short flags -uf → deny" deny $R "git push -uf origin HEAD:main"
expect "combined short flags -vd → deny" deny $R "git push -vd origin old"
expect "-o value isn't a flag cluster" allow $R "git push -odf=1 origin main"
expect "abbreviated --mirr → deny" deny $R "git push --mirr origin"
expect "--force-with-lease=… → deny" deny $R "git push --force-with-lease=main:abc origin main"
expect "-c k=v -C . before push recognised → deny force" deny $R "git -c a=b -C . push -f origin main"
expect "--no-pager before push recognised → deny force" deny $R "git --no-pager push -f origin main"
expect "-C with a quoted dir" deny $S "git -C 'repo' push --force origin main"
expect "/usr/bin/git recognised" deny $R "/usr/bin/git push -f origin main"
expect "push inside bash -c \"…\" → deny force" deny $R "bash -c \"git push -f origin main\""
expect "--git-dir names another repo → deny" deny $R "git --git-dir=$R/.git push origin main"
expect "GIT_DIR= env names another repo → deny" deny $R "GIT_DIR=$R/.git git push origin main"
expect "-c remote.*.mirror → deny" deny $R "git -c remote.origin.mirror=true push origin"
expect "second push in the command is force → deny" deny $R "git push origin main && git push -f origin main"
expect "shell expansion in a refspec → allow (never ask outside workers)" allow $R "git push origin \$BR"
expect "quoted expansion in a refspec → allow" allow $R "git push origin \"\$BR\""
expect "expansion + force → deny" deny $R "git push -f origin \"\$BR\""
expect "&> is a redirection, not a separator → deny force after it" deny $R "git push origin HEAD:main &>/dev/null --force"
expect "&>> likewise" deny $R "git push origin HEAD:main &>> log --force"
expect "&> redirection on a normal push" allow $R "git push origin main &>/dev/null"
expect "--config-env=remote.*=VAR → deny" deny $R "X=true git --config-env=remote.origin.mirror=X push origin"
expect "brace expansion to a +refspec → deny" deny $R "git push origin {+HEAD:main,}"
expect "brace expansion to -f → deny" deny $R "git push {-f,} origin main"
expect "other brace/glob expansion → allow" allow $R "git push origin {main,dev}"
expect "quoted command name still a push" deny $R "\"git\" push -f origin main"
expect ">| is a redirection, not a pipe → deny force after it" deny $R "git push origin HEAD:main >|/dev/null --force"
expect "-c value with a variable isn't a hidden verb (compound: no decision, H4)" silent $R "git -c user.name=\$N push origin main 2>/dev/null; true"
expect "--attr-source <tree> before push recognised → deny force" deny $R "git --attr-source HEAD push -f origin main"
expect "unknown global option with a value before push → allow" allow $R "git --frob val push origin main"
expect "push as a later argument isn't a push" allow $R "git commit -m push"
expect "redirection before the verb → deny force" deny $R "git 2>/dev/null push -f origin main"
expect "bare redirection before the verb → deny force" deny $R "git > /dev/null push --force origin main"
expect "2>&1 before the verb → deny force" deny $R "git 2>&1 push -f origin main"
expect "redirection before the verb, normal push" allow $R "git 2>/dev/null push origin main"
expect "redirection + unknown option before the verb → allow" allow $R "git 2>/dev/null --frob v push origin main"
expect "every unknown-option push is force-checked" deny $R "git --frob v push origin main; git --frob v push -f origin main"
expect "-c include.path → deny" deny $R "git -c include.path=/tmp/m push origin"
expect "the ':' matching refspec isn't a delete" allow $R "git push origin :"

echo "-- main checkout: quoted text given to grep/rg/echo is data; anything else stays a push"
expect "grep for the text git push → silent" silent $R "grep -rn \"git push\" ."
expect "rg for the text → silent" silent $R "rg 'git push origin' skills"
expect "echo of the text → silent" silent $R "echo \"run git push later\""
expect "grep for force text → silent" silent $R "grep -rn \"git push -f\" . | head"
expect "git log --grep text → silent" silent $R "git log --grep \"git push --force\""
expect "commit message with push text → plain commit allow" allow $R "git commit -m \"fix git push -f handling\""
expect "push after a data string → deny force" deny $R "grep \"x\" .; git push -f origin main"
expect "\$((<<)) then a push line → deny" deny $R "echo \"\$((1<<2))\"${NL}git push -f origin main"
expect "((<<)) then a push line → deny" deny $R "((x=1<<2))${NL}git push -f origin main"
expect "\${x// #/} then push → deny" deny $R "echo \${x// #/}; git push -f origin main"
expect "comment quote shifts pairing → deny" deny $R "echo x # \"${NL}grep \"a\"; git push -f origin main; echo \"b\""
expect "\$'…' shifts pairing → deny" deny $R "echo \$'a\\'b${NL}grep '; git push -f origin main; '"
expect "multi-line string → deny" deny $R "echo \"x${NL}grep \"; git push -f origin main; \""
expect "\$(…) inside the data string runs → deny" deny $R "grep \"\$(git push -f origin main)\" ."
expect "data piped to sh → deny" deny $R "echo \"git push -f origin main\" | sh"
expect "data piped to bash → deny" deny $R "echo 'git push -f origin main' | bash"
expect "data piped to /bin/sh → deny" deny $R "echo 'git push -f origin main' | /bin/sh"
expect "data piped to awk system() → deny" deny $R "echo \"git push -f origin main\" | awk '{system(\$0)}'"
expect "force after a \$(…) refspec → deny" deny $R "git push origin \$(git branch --show-current) --force"
expect "force after an empty \$(…) → deny" deny $R "git push origin main \$(echo) -f"
expect "force after \$((…)) → deny" deny $R "git push origin main \$((1)) --force"
expect "force after a backtick refspec → deny" deny $R "git push origin \`git branch --show-current\` --force"
expect "multi-line \$(…) then --force → deny" deny $R "git push origin \$(${NL}  git rev-parse --abbrev-ref HEAD${NL}) --force"
expect "multi-line \$(…) then :delete → deny" deny $R "git push origin \$(${NL}echo x${NL}) :main"
expect "heredoc in \$(…) then -f → deny" deny $R "git push origin \$(cat <<E${NL}main${NL}E${NL}) -f"
expect "multi-line backticks then -f → deny" deny $R "git push origin \`${NL}echo main${NL}\` -f"
expect "\$(…) refspec without force → not denied (substitution: no decision, H4)" silent $R "git push origin \$(git branch --show-current)"
expect "data piped to at → deny" deny $R "echo \"git push -f origin main\" | at now"
expect "data piped to \$SHELL → deny" deny $R "echo \"git push -f origin main\" | \$SHELL"
expect "data piped to sudo -s → deny" deny $R "echo \"git push -f origin main\" | sudo -s"
expect "data piped to a reader → silent" silent $R "grep -rn \"git push -f\" . | sort | head"
expect "escaped backslash before a newline, quoted -f → deny" deny $R "echo x \\\\${NL}git push \"-f\" origin main"
expect "escaped backslash before a newline, quoted :delete → deny" deny $R "echo x \\\\${NL}git push origin \":main\""
expect "dot-sourcing data → deny" deny $R ". <(echo \"git push -f origin main\")"
expect "awk can run its program → deny" deny $R "awk 'BEGIN{system(\"git push -f origin main\")}'"
expect "sed can run its script → deny" deny $R "sed -n 's/a/git push -f origin main/e' a.txt"
expect "function shadowing echo → deny" deny $R "echo(){ \$1; }; echo \"git push -f origin main\""
expect "env prefix isn't the program word → push (allow, no prompt)" allow $R "LC_ALL=C grep \"git push\" ."
expect "words after a data string are still its program's args → silent" silent $R "echo \"git\" push -f origin main"

echo "-- main checkout, tier S unevidenced: a continuation denies (doesn't fall back to ask)"
ok "tier S recorded" "$O tier --set S --repo $R"
expect "tier S, continued push → deny" deny $R "git push origin main ${BS}  -q"
expect "tier S, unparseable push → deny (not ask, not allow)" deny $R "git push origin \$BR"
expect "tier S, unknown option before push → deny" deny $R "git --frob val push origin main"
expect "tier S, grep for push text → silent" silent $R "grep -rn \"git push\" ."

rm -f $R/.git/orchestra-tier.json  # main checkout pushes as today from here on
echo "-- registered worker with gates-ok + merge lock: exactly origin HEAD:<target>"
RUN=$($O new-run --repo $R --title t --coordinator workspace:0); $O run-branch --run $RUN >/dev/null; T=orch/$RUN
git fetch -q; git worktree add -q $S/w -b w origin/$T; W=$S/w
ok "register" "$O register --worktree $W --run $RUN --slice s1"
cd $W; echo c > c.txt; git add .; git commit -qm s1; git branch other
ok "gates" "$O gates --worktree $W --cmd 'bash gate.sh'"
ok "reviewer PASS" "$O $V --worktree $W --role reviewer --verdict PASS"
ok "verifier PASS" "$O $V --worktree $W --role verifier --verdict PASS"
ok "gates-ok" "$O gates-ok --worktree $W"
ok "merge lock" "$O merge-lock --repo $W --owner $RUN-s1 --wait 0"
expect "the one allowed form" allow $W "git push origin HEAD:$T"
expect "full-ref target + -u + redirections" allow $W "git push -u origin HEAD:refs/heads/$T >/dev/null 2>&1"
expect "global options before push" allow $S "git --no-pager -c color.ui=never -C $W push -q origin HEAD:$T"
expect "continuation joined" allow $W "git push origin ${BS}  HEAD:$T"
expect "quoted +HEAD refspec → deny" deny $W "git push origin \"+HEAD:$T\""
expect "-uf → deny" deny $W "git push -uf origin HEAD:$T"
expect "source other than HEAD → deny" deny $W "git push origin other:$T"
expect "@ alias for HEAD → deny" deny $W "git push origin @:$T"
expect "second refspec → deny" deny $W "git push origin HEAD:$T other:refs/heads/x"
expect "continuation adds a refspec → deny" deny $W "git push origin HEAD:$T ${BS}  other:refs/heads/x"
expect "continuation adds --force → deny" deny $W "git push origin HEAD:$T ${BS}  --force"
expect "-c/-C before push recognised → deny force" deny $W "git -c a=b -C . push -f origin HEAD:$T"
expect "--no-pager before push recognised → deny force" deny $W "git --no-pager push -f origin HEAD:$T"
expect "--repo overrides the remote → deny" deny $W "git push --repo=elsewhere origin HEAD:$T"
expect "--receive-pack → deny" deny $W "git push --receive-pack=x origin HEAD:$T"
expect "unknown option → deny" deny $W "git push --frobnicate origin HEAD:$T"
expect "unbalanced quote → deny" deny $W "git push origin \"HEAD:$T"
expect "shell expansion → deny" deny $W "git push origin HEAD:\$T"
expect "remote other than origin → deny" deny $W "git push upstream HEAD:$T"
expect "--force after &> → deny" deny $W "git push origin HEAD:$T &>/dev/null --force"
expect "second refspec after &> → deny" deny $W "git push origin HEAD:$T &>/dev/null other:refs/heads/x"
expect "&> redirection on the allowed form" allow $W "git push origin HEAD:$T &>/dev/null"
expect "brace expansion → deny" deny $W "git push origin HEAD:{$T,x}"
expect "quoted verb → deny" deny $W "git 'push' origin other:$T"
expect "double-quoted verb → deny" deny $W "git \"push\" origin HEAD:$T"
expect "escaped verb → deny" deny $W "git p\\ush origin HEAD:$T"
expect "empty quotes after git → deny" deny $W "git\"\" push origin other:$T"
expect "a vanishing x\\git match doesn't cancel a hidden push" deny $W "x\\git push origin HEAD:$T; git 'push' origin other:$T"
expect "quoted -c decoy doesn't cancel a hidden push" deny $W "git -c 'x.y=a b' push origin HEAD:$T; git 'push' origin other:$T"
expect "ANSI-C quoted verb → deny" deny $W "git \$'push' origin other:$T"
expect "brace-built push → deny" deny $W "git {push,origin,other:$T}"
expect "xargs feeding git push → deny" deny $W "echo other:$T | xargs git push origin"
expect "\$(…) in a push command → deny" deny $W "git push origin \$(echo HEAD:$T)"
expect "\${…} in a push command → deny" deny $W "git push origin HEAD:\${T}"
expect "backticks in a push command → deny" deny $W "git push origin \`echo HEAD:$T\`"
expect "eval → deny" deny $W "eval git push origin HEAD:$T"
expect "sh -c → deny" deny $W "sh -c 'git push origin HEAD:$T'"
expect "bash -c → deny" deny $W "bash -c 'git push origin HEAD:$T'"
expect "alias → deny" deny $W "alias p='git push'; p origin HEAD:$T"
expect "locale-quoted verb → deny" deny $W "git \$\"push\" origin HEAD:$T"
expect "--attr-source before push → deny non-HEAD source" deny $W "git --attr-source HEAD push origin other:$T"
expect "redirection before the verb → deny non-HEAD source" deny $W "git 2>/dev/null push origin other:$T"
expect "redirection before the verb → still the full worker checks" allow $W "git 2>/dev/null push origin HEAD:$T"
expect "unknown global option before push → deny" deny $W "git --frob val push origin HEAD:$T"
expect "-C to the main checkout from a worker → deny" deny $W "git -C $R push origin HEAD:main"
expect "heredoc commit message mentioning push isn't a push" silent $W "git commit -qm \"\$(cat <<'EOF'${NL}fix push check${NL}EOF${NL})\""
expect "heredoc fed to a shell is still checked" deny $W "bash <<'EOF'${NL}git push origin other:$T${NL}EOF"
expect "cat heredoc piped to a shell is still checked" deny $W "cat <<'EOF' | bash${NL}git \$'push' origin other:$T${NL}EOF"
expect "the cat heredoc's opener line is still checked" deny $W "cat <<EOF >/dev/null; eval \"git pu\"\"sh origin other:$T\"${NL}msg${NL}EOF"
expect "indirection without push isn't a push" silent $W "echo \$(date) push-guard notes"
expect "quoted '>' is a word, not a redirection → deny" deny $W "git push origin HEAD:$T '>' other:refs/heads/x"
expect "quoted '2>' doesn't hide an option → deny" deny $W "git push origin HEAD:$T '2>' --receive-pack=x"

echo "-- worker: quoted text is data; the session cwd decides 'inside a worker'"
expect "worker grep for push text → silent" silent $W "grep -rn \"git push\" ."
expect "worker rg for push text → silent" silent $W "rg 'git push origin' skills"
expect "worker echo of push text → silent" silent $W "echo \"run git push later\""
expect "worker commit message with push + \$X → silent" silent $W "git commit -m \"push \$X\""
expect "echo then the allowed push → deny (worker pushes are one plain command)" deny $W "echo \"done\" && git push origin HEAD:$T"
expect "worker \$((<<)) then a push line → deny" deny $W "echo \"\$((n<<1))\"${NL}git push origin other:$T"
expect "worker commit msg then a real push → deny" deny $W "git commit -m \"fix push\" && git push origin other:$T"
expect "worker data captured by \$(…) → deny" deny $W "P=\$(echo \"push\"); git \$P origin other:$T"
expect "worker data read into a variable → deny" deny $W "echo \"push\" | { read P; git \$P origin other:$T; }"
expect "worker printf -v builds the verb → deny" deny $W "printf -v P \"push\"; git \$P origin other:$T"
expect "worker cd to the main checkout → deny" deny $W "cd $R && git push origin HEAD:main"
expect "worker cd later in the command → deny" deny $W "true; cd $R; git push origin HEAD:$T"
expect "worker data piped to make → deny" deny $W "echo \"x: ; git push origin other:$T\" | make -f -"
expect "worker zsh chdir → deny" deny $W "chdir $R && git push origin HEAD:$T"
expect "worker pushd → deny" deny $W "pushd $R; git push origin HEAD:$T"
expect "worker leading cd into its own worktree → allow" allow $W "cd $W && git push origin HEAD:$T"
expect "worker leading cd into its own worktree, then more → deny (one plain command)" deny $W "cd $W && git push origin HEAD:$T; true"
expect "worker cd own worktree, then cd away → deny" deny $W "cd $W && cd $R && git push origin HEAD:$T"

echo; echo "PASSED $P  FAILED $F"; [ $F = 0 ]
